-- 0001.baseline-schema  (dialeto PostgreSQL)
-- Estado consolidado do schema: tabelas + índices + views.
-- Convergente (CREATE TABLE IF NOT EXISTS / CREATE OR REPLACE VIEW): seguro rodar
-- num banco vazio. Tabelas em ordem de dependência (sem desabilitar FK check).
--
-- Migrado de MySQL 8 para PostgreSQL 16 na issue #115. As 3 views de cálculo
-- pesado (v_gmd_analitico, v_fluxo_caixa, vw_resultado_lote) viram MATERIALIZED
-- VIEW na 0003 — aqui ficam como view normal para o CREATE ser convergente.
-- Política só-aditiva de schema (#78): migrações seguintes nunca dão DROP.

CREATE TABLE IF NOT EXISTS usuarios (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      varchar(50)  NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    email         varchar(255) UNIQUE,
    created_at    timestamptz  DEFAULT now()
);

CREATE TABLE IF NOT EXISTS lotes (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            integer NOT NULL REFERENCES usuarios(id),
    codigo_lote        varchar(50)  NOT NULL,
    descricao          varchar(200),
    data_aquisicao     date NOT NULL,
    custo_medio_cabeca numeric(10,2),
    created_at         timestamptz DEFAULT now(),
    deleted_at         timestamptz
);
CREATE INDEX IF NOT EXISTS idx_lotes_user ON lotes (user_id);

CREATE TABLE IF NOT EXISTS animais (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brinco          varchar(50) NOT NULL,
    sexo            char(1) NOT NULL,
    raca            varchar(100),
    data_compra     date,
    preco_compra    numeric(10,2),
    data_venda      date,
    preco_venda     numeric(10,2),
    user_id         integer NOT NULL REFERENCES usuarios(id),
    deleted_at      timestamptz,
    lote_id         integer REFERENCES lotes(id),
    pai_id          integer REFERENCES animais(id) ON DELETE SET NULL,
    mae_id          integer REFERENCES animais(id) ON DELETE SET NULL,
    data_nascimento date,
    UNIQUE (brinco, user_id)
);
CREATE INDEX IF NOT EXISTS idx_animais_venda        ON animais (user_id, data_venda);
CREATE INDEX IF NOT EXISTS idx_animais_ativo        ON animais (user_id, deleted_at);
CREATE INDEX IF NOT EXISTS idx_animais_ativo_venda  ON animais (user_id, deleted_at, data_venda);
CREATE INDEX IF NOT EXISTS idx_animais_brinco       ON animais (user_id, deleted_at, brinco);
CREATE INDEX IF NOT EXISTS idx_animais_lote         ON animais (lote_id, deleted_at);
CREATE INDEX IF NOT EXISTS idx_animais_raca         ON animais (user_id, raca, deleted_at);
CREATE INDEX IF NOT EXISTS idx_animais_pai          ON animais (pai_id);
CREATE INDEX IF NOT EXISTS idx_animais_mae          ON animais (mae_id);

CREATE TABLE IF NOT EXISTS pesagens (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id    integer NOT NULL REFERENCES animais(id),
    data_pesagem date NOT NULL,
    peso         numeric(10,2) NOT NULL,
    deleted_at   timestamptz
);
CREATE INDEX IF NOT EXISTS idx_pesagens_otimizada ON pesagens (animal_id, data_pesagem);
CREATE INDEX IF NOT EXISTS idx_pesagens_max       ON pesagens (animal_id, id DESC);

CREATE TABLE IF NOT EXISTS medicacoes (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id        integer NOT NULL REFERENCES animais(id),
    data_aplicacao   date NOT NULL,
    nome_medicamento varchar(100) NOT NULL,
    custo            numeric(10,2),
    observacoes      text,
    deleted_at       timestamptz
);
CREATE INDEX IF NOT EXISTS idx_med_busca ON medicacoes (animal_id, data_aplicacao);

CREATE TABLE IF NOT EXISTS custos_operacionais (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     integer NOT NULL REFERENCES usuarios(id),
    categoria   varchar(20) NOT NULL,
    tipo_custo  varchar(50) NOT NULL,
    valor       numeric(10,2) NOT NULL,
    data_custo  date NOT NULL,
    descricao   text,
    deleted_at  timestamptz
);
CREATE INDEX IF NOT EXISTS idx_custos_busca          ON custos_operacionais (user_id, data_custo);
CREATE INDEX IF NOT EXISTS idx_custos_user_del_data  ON custos_operacionais (user_id, deleted_at, data_custo);

CREATE TABLE IF NOT EXISTS configuracoes (
