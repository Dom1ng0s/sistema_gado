-- ============================================================================
-- Views: cálculo pesado (GMD, fluxo de caixa, P&L, ocupação) delegado ao banco.
-- ============================================================================

CREATE OR REPLACE VIEW v_gmd_analitico AS
WITH pesagens_ordenadas AS (
    SELECT animal_id, data_pesagem, peso,
        ROW_NUMBER() OVER (PARTITION BY animal_id ORDER BY data_pesagem ASC)  AS rn_asc,
        ROW_NUMBER() OVER (PARTITION BY animal_id ORDER BY data_pesagem DESC) AS rn_desc
    FROM pesagens
    WHERE deleted_at IS NULL
),
primeira_ultima AS (
    SELECT animal_id,
        MAX(data_pesagem) FILTER (WHERE rn_asc  = 1) AS data_inicial,
        MAX(peso)         FILTER (WHERE rn_asc  = 1) AS peso_inicial,
        MAX(data_pesagem) FILTER (WHERE rn_desc = 1) AS data_final,
        MAX(peso)         FILTER (WHERE rn_desc = 1) AS peso_final
    FROM pesagens_ordenadas
    GROUP BY animal_id
)
SELECT
    a.user_id, a.id AS animal_id, a.brinco,
    p.peso_final,
    (p.peso_final - p.peso_inicial) AS ganho_total,
    (p.data_final - p.data_inicial) AS dias,
    -- gmd NULL para animal com pesagens só na mesma data (idêntico ao cálculo
    -- inline que as consultas de rebanho/painel faziam antes do #115).
    CASE WHEN (p.data_final - p.data_inicial) > 0
         THEN (p.peso_final - p.peso_inicial) / (p.data_final - p.data_inicial)
         END AS gmd
FROM primeira_ultima p
JOIN animais a ON p.animal_id = a.id
WHERE a.deleted_at IS NULL;

CREATE OR REPLACE VIEW v_fluxo_caixa AS
SELECT user_id, ano,
       SUM(receita)         AS total_entradas,
       SUM(despesa_compra)  AS total_compras,
       SUM(despesa_med)     AS total_med,
       SUM(despesa_ops)     AS total_ops
FROM (
    SELECT user_id, EXTRACT(YEAR FROM data_venda)::int AS ano,
           preco_venda AS receita, 0 AS despesa_compra, 0 AS despesa_med, 0 AS despesa_ops
    FROM animais
    WHERE data_venda IS NOT NULL AND deleted_at IS NULL
    UNION ALL
    SELECT user_id, EXTRACT(YEAR FROM data_compra)::int,
           0, preco_compra, 0, 0
    FROM animais
    WHERE deleted_at IS NULL AND data_compra IS NOT NULL
    UNION ALL
    SELECT a.user_id, EXTRACT(YEAR FROM m.data_aplicacao)::int,
           0, 0, m.custo, 0
    FROM medicacoes m
    JOIN animais a ON m.animal_id = a.id
    WHERE m.deleted_at IS NULL AND a.deleted_at IS NULL
    UNION ALL
    SELECT user_id, EXTRACT(YEAR FROM data_custo)::int,
           0, 0, 0, valor
    FROM custos_operacionais
    WHERE deleted_at IS NULL
) uniao_geral
GROUP BY user_id, ano;

CREATE OR REPLACE VIEW vw_resultado_lote AS
SELECT
    l.id AS lote_id, l.user_id, l.codigo_lote, l.descricao, l.data_aquisicao,
    COUNT(a.id) AS total_animais,
    COALESCE(SUM(a.preco_compra), 0) AS custo_aquisicao,
    COALESCE(SUM(a.preco_venda) FILTER (WHERE a.data_venda IS NOT NULL), 0) AS receita_vendas,
    COALESCE(SUM(med.custo_med), 0) AS custo_medicacoes,
    COUNT(*) FILTER (WHERE a.data_venda IS NOT NULL) AS animais_vendidos,
    (COALESCE(SUM(a.preco_venda) FILTER (WHERE a.data_venda IS NOT NULL), 0)
     - COALESCE(SUM(a.preco_compra), 0)
     - COALESCE(SUM(med.custo_med), 0)) AS margem_bruta
FROM lotes l
JOIN animais a ON a.lote_id = l.id AND a.deleted_at IS NULL
LEFT JOIN (
    SELECT animal_id, SUM(custo) AS custo_med
    FROM medicacoes WHERE deleted_at IS NULL
    GROUP BY animal_id
) med ON med.animal_id = a.id
WHERE l.deleted_at IS NULL
GROUP BY l.id, l.user_id, l.codigo_lote, l.descricao, l.data_aquisicao;

CREATE OR REPLACE VIEW vw_saldo_estoque AS
SELECT
    p.id AS produto_id, p.user_id, p.nome, p.unidade, p.categoria, p.estoque_minimo,
    COALESCE(SUM(CASE WHEN m.tipo = 'entrada' THEN m.quantidade ELSE 0 END), 0) AS total_entradas,
    COALESCE(SUM(CASE WHEN m.tipo = 'saida'   THEN m.quantidade ELSE 0 END), 0) AS total_saidas,
    COALESCE(SUM(CASE WHEN m.tipo = 'entrada' THEN m.quantidade ELSE -m.quantidade END), 0) AS saldo_atual,
    CASE WHEN COALESCE(SUM(CASE WHEN m.tipo = 'entrada' THEN m.quantidade ELSE -m.quantidade END), 0)
              < p.estoque_minimo THEN 1 ELSE 0 END AS abaixo_minimo,
    MIN(m.data_validade) FILTER (WHERE m.tipo = 'entrada' AND m.data_validade IS NOT NULL) AS proxima_validade,
    CASE WHEN MIN(m.data_validade) FILTER (WHERE m.tipo = 'entrada' AND m.data_validade IS NOT NULL)
              < CURRENT_DATE THEN 1 ELSE 0 END AS tem_vencido
FROM estoque_produtos p
LEFT JOIN estoque_movimentacoes m ON m.produto_id = p.id
GROUP BY p.id, p.user_id, p.nome, p.unidade, p.categoria, p.estoque_minimo;

CREATE OR REPLACE VIEW vw_ocupacao_atual AS
SELECT
    m.id AS modulo_id, m.pasto_id, m.user_id, m.nome AS modulo_nome, m.capacidade_ua,
    o.id AS ocupacao_id, o.data_entrada,
    COUNT(oa.animal_id) AS ua_atual,
    ROUND(COUNT(oa.animal_id) / NULLIF(m.capacidade_ua, 0) * 100, 1) AS pct_lotacao
FROM modulos m
JOIN ocupacoes o ON o.modulo_id = m.id AND o.data_saida IS NULL
JOIN ocupacao_animais oa ON oa.ocupacao_id = o.id
GROUP BY m.id, m.pasto_id, m.user_id, m.nome, m.capacidade_ua, o.id, o.data_entrada;

CREATE OR REPLACE VIEW vw_dias_descanso AS
SELECT
    m.id AS modulo_id, m.pasto_id, m.user_id, m.nome AS modulo_nome,
    MAX(o.data_saida) AS ultima_saida,
    (CURRENT_DATE - MAX(o.data_saida)) AS dias_descanso
FROM modulos m
LEFT JOIN ocupacoes o ON o.modulo_id = m.id AND o.data_saida IS NOT NULL
WHERE m.id NOT IN (SELECT modulo_id FROM ocupacoes WHERE data_saida IS NULL)
GROUP BY m.id, m.pasto_id, m.user_id, m.nome;

CREATE OR REPLACE VIEW vw_gmd_por_modulo AS
WITH oa_rel AS (
    SELECT o.modulo_id, m.nome AS modulo_nome, m.pasto_id, m.user_id, oa.animal_id
    FROM ocupacoes o
    JOIN ocupacao_animais oa ON oa.ocupacao_id = o.id
    JOIN modulos m ON m.id = o.modulo_id
),
po AS (
    SELECT p.animal_id, p.data_pesagem, p.peso,
        ROW_NUMBER() OVER (PARTITION BY p.animal_id ORDER BY p.data_pesagem ASC)  AS rn_asc,
        ROW_NUMBER() OVER (PARTITION BY p.animal_id ORDER BY p.data_pesagem DESC) AS rn_desc
    FROM pesagens p
    JOIN oa_rel r ON r.animal_id = p.animal_id
    WHERE p.deleted_at IS NULL
),
pu AS (
    SELECT animal_id,
        MAX(data_pesagem) FILTER (WHERE rn_asc  = 1) AS data_ini,
        MAX(peso)         FILTER (WHERE rn_asc  = 1) AS peso_ini,
        MAX(data_pesagem) FILTER (WHERE rn_desc = 1) AS data_fim,
        MAX(peso)         FILTER (WHERE rn_desc = 1) AS peso_fim
    FROM po GROUP BY animal_id
),
gmd_calc AS (
    SELECT animal_id,
        CASE WHEN (data_fim - data_ini) > 0
             THEN (peso_fim - peso_ini) / (data_fim - data_ini)
             ELSE NULL END AS gmd
    FROM pu WHERE data_ini <> data_fim
)
SELECT
    r.modulo_id, r.modulo_nome, r.pasto_id, r.user_id,
    COUNT(DISTINCT r.animal_id) AS qtd_animais,
    ROUND(AVG(g.gmd), 3) AS gmd_medio
FROM oa_rel r
LEFT JOIN gmd_calc g ON g.animal_id = r.animal_id
GROUP BY r.modulo_id, r.modulo_nome, r.pasto_id, r.user_id;

CREATE OR REPLACE VIEW vw_historico_vaca AS
SELECT
    r.vaca_id, a.user_id,
    COUNT(*) AS total_coberturas,
    SUM(CASE WHEN r.resultado = 'vivo' THEN 1 ELSE 0 END) AS partos_vivos,
    ROUND(SUM(CASE WHEN r.resultado = 'vivo' THEN 1 ELSE 0 END)::numeric / COUNT(*) * 100, 1) AS taxa_sucesso,
    MIN(r.data_cobertura) AS primeira_cobertura,
    MAX(r.data_cobertura) AS ultima_cobertura
FROM reproducao r
JOIN animais a ON r.vaca_id = a.id
GROUP BY r.vaca_id, a.user_id;

CREATE OR REPLACE VIEW vw_partos_previstos AS
SELECT
    r.id, r.user_id, r.vaca_id,
    v.brinco AS vaca_brinco,
    r.data_cobertura,
    r.data_parto_prevista,
    r.diagnostico,
    (r.data_parto_prevista - CURRENT_DATE) AS dias_restantes
FROM reproducao r
JOIN animais v ON r.vaca_id = v.id AND v.deleted_at IS NULL
WHERE r.diagnostico = 'positivo'
  AND r.data_parto IS NULL
  AND r.data_parto_prevista IS NOT NULL;
