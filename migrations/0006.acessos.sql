-- 0006.acessos  (SGG+ PR 3)
-- Até aqui "usuário" e "fazenda" eram a mesma coisa: `animais.user_id` era ao
-- mesmo tempo quem logou e de quem é o rebanho. Isso torna impossível um
-- vaqueiro, um contador ou um consultor entrar sem receber a senha do dono —
-- que é como o sistema é usado hoje na prática. Esta migration separa as duas
-- ideias: a conta continua em `usuarios`, e `acessos_fazenda` diz a quais
-- fazendas essa conta tem acesso e em que papel.

-- Revogação e desativação de conta. O loader filtra por `ativo = 1`, então
-- desligar alguém passa a valer no request seguinte, não no vencimento do
-- cookie.
ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS ativo smallint NOT NULL DEFAULT 1;

-- `papel` NÃO fica em `usuarios`: `dono` é simplesmente quem não tem linha
-- ativa aqui. Isso dá de graça o consultor que atende N fazendas (N linhas, em
-- vez de uma coluna que não teria como representar isso) e evita um papel
-- default mentiroso em toda conta existente.
CREATE TABLE IF NOT EXISTS acessos_fazenda (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_user_id integer NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    owner_user_id   integer NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    papel           varchar(20) NOT NULL
                    CHECK (papel IN ('vaqueiro','contador','consultor')),
    ativo           smallint NOT NULL DEFAULT 1,
    created_at      timestamptz DEFAULT now(),
    UNIQUE (account_user_id, owner_user_id)
);

-- O CASCADE dos dois lados é proposital: apagar a conta do vaqueiro tira o
-- acesso dele, e apagar a do dono não deixa acesso órfão apontando para uma
-- fazenda que não existe mais. `delete_user_and_data` não precisa saber da
-- tabela.

-- Índice do caminho quente: o loader resolve a fazenda em TODO request.
CREATE INDEX IF NOT EXISTS ix_acessos_conta ON acessos_fazenda (account_user_id, ativo);

-- Quem registrou a linha, que deixa de ser dedutível de `user_id` no momento em
-- que o dono não é mais o único que escreve. Entram agora porque a migration é
-- aditiva e barata; enquanto só existe `dono`, `registrado_por` seria igual a
-- `user_id` em toda linha — o valor aparece junto com o fluxo de convite.
--
-- ON DELETE SET NULL, não RESTRICT: o vaqueiro que pesou 200 animais tem de
-- poder apagar a própria conta sem travar em FK, e sem levar embora a pesagem,
-- que é dado do dono.
ALTER TABLE pesagens              ADD COLUMN IF NOT EXISTS registrado_por integer REFERENCES usuarios(id) ON DELETE SET NULL;
ALTER TABLE medicacoes            ADD COLUMN IF NOT EXISTS registrado_por integer REFERENCES usuarios(id) ON DELETE SET NULL;
ALTER TABLE custos_operacionais   ADD COLUMN IF NOT EXISTS registrado_por integer REFERENCES usuarios(id) ON DELETE SET NULL;
ALTER TABLE estoque_movimentacoes ADD COLUMN IF NOT EXISTS registrado_por integer REFERENCES usuarios(id) ON DELETE SET NULL;
