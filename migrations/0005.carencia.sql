-- 0005.carencia  (SGG+ PR 1)
-- Carência sanitária: o intervalo entre a aplicação de um medicamento e a data
-- em que a carcaça pode ir para o abate. Hoje o dado não existe em lugar nenhum
-- do sistema — o prazo mora na bula, na cabeça do vaqueiro, e a venda sai sem
-- ninguém perguntar. Uma carcaça rejeitada no frigorífico é o custo do animal
-- inteiro mais o frete.
--
-- `dias_carencia` fica em `medicacoes`, não em `protocolos_sanitarios`: não há
-- FK de medicação para protocolo, então um padrão por protocolo não tem caminho
-- até a aplicação. O valor é sugerido no formulário (utils/carencia.py) e
-- gravado na linha da aplicação, que é onde a data de liberação se calcula.

ALTER TABLE medicacoes
    ADD COLUMN IF NOT EXISTS dias_carencia integer NOT NULL DEFAULT 0
        CHECK (dias_carencia >= 0);

-- View normal, não matview: depende de CURRENT_DATE, e uma matview com refresh
-- de 5 minutos liberaria (ou travaria) animal na virada do dia pela metade.
CREATE OR REPLACE VIEW vw_animais_em_carencia AS
SELECT a.user_id, a.id AS animal_id, a.brinco,
       m.id AS medicacao_id, m.nome_medicamento, m.data_aplicacao, m.dias_carencia,
       (m.data_aplicacao + m.dias_carencia)                  AS data_liberacao,
       ((m.data_aplicacao + m.dias_carencia) - CURRENT_DATE) AS dias_restantes
FROM medicacoes m
JOIN animais a ON a.id = m.animal_id
WHERE m.deleted_at IS NULL AND a.deleted_at IS NULL AND a.data_venda IS NULL
  AND m.dias_carencia > 0
  AND (m.data_aplicacao + m.dias_carencia) > CURRENT_DATE;

-- Índice parcial: a esmagadora maioria das medicações é carência zero (vitamina,
-- vacina sem prazo), e a guarda da venda só olha as que têm prazo.
CREATE INDEX IF NOT EXISTS ix_med_carencia
    ON medicacoes (animal_id, data_aplicacao) WHERE dias_carencia > 0;

-- O override é a única evidência que existe se a carcaça for rejeitada: quem
-- autorizou, qual animal, qual aplicação e qual data foi furada.
CREATE TABLE IF NOT EXISTS vendas_com_carencia (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id      integer NOT NULL REFERENCES animais(id),
    medicacao_id   integer NOT NULL REFERENCES medicacoes(id),
    autorizado_por integer NOT NULL REFERENCES usuarios(id),
    data_liberacao date NOT NULL,
    created_at     timestamptz DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_vendas_carencia_animal
    ON vendas_com_carencia (animal_id);
