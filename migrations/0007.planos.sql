-- 0007.planos  (SGG+ PR 4)
-- Assinatura, manual primeiro. O sistema não tem nenhuma noção de plano: toda
-- conta vale o mesmo e nada distingue quem paga de quem está testando. Esta
-- migration dá à fazenda um tier, um status e um limite de cabeças, e abre
-- `pagamentos` para o histórico — mas a cobrança em si continua fora: link de
-- pagamento Asaas e ativação manual. O webhook é um PR próprio, e não entra no
-- caminho crítico desta sprint.
--
-- O plano mora em `configuracoes` (chave `user_id`) porque é atributo da
-- fazenda, não da conta: um vaqueiro convidado não tem plano, ele opera dentro
-- do plano do dono. Com `farm_id` do PR 3, a leitura cai no lugar certo sem
-- nenhuma junção nova.

ALTER TABLE configuracoes
    ADD COLUMN IF NOT EXISTS plano_tier     varchar(20) NOT NULL DEFAULT 'trial',
    ADD COLUMN IF NOT EXISTS plano_status   varchar(20) NOT NULL DEFAULT 'ativo',
    ADD COLUMN IF NOT EXISTS trial_ends_at  timestamptz,
    ADD COLUMN IF NOT EXISTS limite_cabecas integer NOT NULL DEFAULT 250;

-- `trial_ends_at` fica SEM default de propósito: os 14 dias são carimbados
-- explicitamente no cadastro (routes/auth.py, que já insere a linha de
-- `configuracoes` — toda conta tem uma). Um default de coluna teria dado a
-- mesma data de vencimento para todas as contas que já existem.
--
-- E quem já existe não entra em trial retroativo: a conta que estava aberta
-- ontem não pode acordar hoje com 14 dias para pagar.
UPDATE configuracoes
   SET plano_tier = 'porteira', trial_ends_at = NULL
 WHERE trial_ends_at IS NULL;

-- Histórico de cobrança. Entra agora, vazia, porque o UNIQUE é o que vai
-- tornar o webhook idempotente quando ele chegar: provider reenvia o mesmo
-- evento até receber 200, e sem essa restrição o reenvio viraria pagamento
-- duplicado. `payload` guarda o evento cru — quando a conciliação não fechar,
-- é a única fonte do que o provider realmente mandou.
CREATE TABLE IF NOT EXISTS pagamentos (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           integer NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    provider          varchar(20) NOT NULL,
    provider_event_id varchar(120) NOT NULL,
    valor             numeric(10,2),
    status            varchar(20) NOT NULL,
    payload           jsonb,
    created_at        timestamptz DEFAULT now(),
    UNIQUE (provider, provider_event_id)
);

CREATE INDEX IF NOT EXISTS ix_pagamentos_user ON pagamentos (user_id, created_at DESC);

-- O limite de cabeças é cobrado na escrita (cadastro, lote, importação), então
-- a consulta que ele faz é "quantas cabeças ativas esta fazenda tem".
CREATE INDEX IF NOT EXISTS ix_animais_ativos_por_user
    ON animais (user_id) WHERE deleted_at IS NULL AND data_venda IS NULL;
